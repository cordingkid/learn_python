## 클로저
"""
클로저란 외부 함수의 변수를 기억하는 내부 함수를 말한다.

예를 들어, 함수 A 안에 함수 B가 있고, 함수 B가 함수 A의 변수를 사용한다고 하자. 
보통은 함수 A가 끝나면 함수 A의 변수도 사라진다. 
하지만 클로저에서는 함수 A가 끝나도 함수 B가 함수 A의 변수를 계속 사용할 수 있다. 
마치 함수 A의 변수가 함수 B 안에 저장되어 있는 것처럼 말이다.

어떤 수에 항상 3을 곱해 반환하는 함수를 생각해 보자. 아마도 다음과 같은 함수를 만들 수 있을 것이다.

def mul3(n):
    return n * 3
mul3() 함수는 입력으로 받은 수 n에 항상 3을 곱하여 반환한다. 

이번에는 항상 5를 곱하여 반환하는 함수를 생각해 보자.

def mul5(n):
    return n * 5

이처럼 mul5() 함수를 만들 수 있을 것이다. 
하지만 필요할 때마다 mul6(), mul7(), mul8(), …과 같은 함수를 만드는 것은 매우 비효율적이다. 
이 문제를 효율적으로 해결하려면 다음과 같이 클래스를 사용하면 된다.
"""

"""
class Mul:
    def __init__(self, m):
        self.m = m

    def mul(self, n):
        return self.m * n

if __name__ == "__main__":
    mul3 = Mul(3)
    mul5 = Mul(5)

    print(mul3.mul(10))
    print(mul5.mul(10))
"""
"""
클래스를 이용해 특정 값을 미리 설정하고 그다음부터 mul() 메서드를 사용하면 원하는 형태로 호출할 수 있다. 
__call__ 메서드를 이용하면 다음과 같이 개선할 수도 있다.
"""

class Mul:
    def __init__(self, m):
        self.m = m

    def __call__(self, n):
        return self.m * n

if __name__ == "__main__":
    mul3 = Mul(3)
    mul5 = Mul(5)

    print(mul3(10))
    print(mul5(10))

"""
mul() 함수의 이름을 __call__로 바꾸었다. 
__call__은 객체를 함수처럼 호출할 수 있게 해주는 특수 메서드이다. 
즉, mul3(10)처럼 객체 뒤에 괄호를 붙여 호출하면 파이썬이 자동으로 __call__ 메서드를 실행한다. 
이전 코드에서는 mul3.mul(10)처럼 메서드 이름을 명시해야 했지만, __call__을 사용하면 mul3(10)처럼 간결하게 호출할 수 있다.

이렇게 클래스로 만드는 방법이 일반적이긴 하지만, 더 간편한 방법이 있다. 다음 함수를 살펴보자.
"""
def mul(m):
    def wrapper(n):
        return m * n
    return wrapper

if __name__ == "__main__":
    mul3 = mul(3)
    mul5 = mul(5)

    print(mul3(10))  # 30 출력
    print(mul5(10))  # 50 출력

"""
외부 함수 mul 안에 내부 함수 wrapper를 구현했다. 
그리고 외부 함수는 내부 함수 wrapper를 반환한다. 
함수가 함수를 반환하는 것이 생소할 수 있겠지만, 파이썬에서 함수는 숫자나 문자열처럼 변수에 저장하거나 다른 함수의 입력으로 전달하거나 반환할 수 있는 객체이므로 이런 사용이 가능하다.

클로저의 핵심은 바로 여기에 있다! mul(3)을 호출하면 외부 함수 mul은 종료되지만, 
반환된 wrapper 함수는 여전히 m=3 값을 기억하고 있다. 
이후 mul3(10)을 호출하면 wrapper 함수가 기억하고 있던 m=3 값을 사용해서 3 * 10 = 30을 계산한다.

즉, 클로저는 함수가 생성될 때의 환경(변수 값)을 기억하는 특별한 함수라고 할 수 있다. 
여기서 반환된 wrapper 함수가 바로 클로저이다. 
그리고 mul 함수처럼 클로저를 만들어내는 함수를 클로저 팩토리(closure factory) 함수라고 한다. 
공장(factory)에서 제품을 찍어내듯이, 클로저 팩토리 함수는 호출할 때마다 새로운 클로저를 만들어 낸다.
"""
