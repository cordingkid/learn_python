## 제너레이터 활용하기
# 제너레이터가 실제로 어떤 도움이 되는지 구체적인 예제로 알아보기

# 상황: 시간이 오래 걸리는 작업을 처리해야 하는데, 모든 결과가 필요하지 않은 경우

# 일반적인 리스트 컴프리헨션을 사용한 예제
import time

def longtime_job():
    print("job start")
    time.sleep(1)
    return "done"

# 리스트 컴프리헨샨: 5번의 작업을 모두 실행해서 리스트로 만든다.
#list_job = [longtime_job() for i in range(5)]
#print(list_job[0]) # 첫 번쨰 결과만 필요한 상황

# 해당 코드를 실행하면 5초가 걸리고 "job start"가 5번 출력된 후 "done"이 출력된다.

# 같은 작업을 제너레이터로 변경
gen_job = (longtime_job() for i in range(5))
print(next(gen_job))
"""
수행 시간도 1초로 단축되었다.

핵심 차이점:

[ ] (리스트 컴프리헨션)을 ( ) (제너레이터 표현식)으로 변경했다.
list_job[0]을 next(gen_job)으로 변경하여 값을 가져왔다.
제너레이터의 동작 방식:

(longtime_job() for i in range(5))는 코드를 즉시 실행하지 않는다. 
next(gen_job)을 호출할 때 비로소 첫 번째 longtime_job()만 실행한다. 
나머지 4개는 실행되지 않는다.

제너레이터를 사용하면 성능이 크게 개선된다. 
실행 시간이 5초에서 1초로 단축되었다. 
리스트 컴프리헨션에서는 5개의 함수를 모두 실행했지만, 
제너레이터 표현식에서는 필요한 첫 번째 함수만 실행했기 때문이다. 
"job start"가 5번 출력되던 것이 1번만 출력되는 것을 보면 함수 호출 횟수가 줄어든 것을 확인할 수 있다. 
메모리 사용량도 절약되는데, 리스트는 모든 결과를 메모리에 저장하지만 제너레이터는 필요할 때만 값을 생성하기 때문이다.

이런 방식을 '느긋한 계산법(lazy evaluation)'이라고 한다. 
미리 모든 값을 만들어 두지 않고 필요한 시점에 비로소 값을 계산한다는 뜻이다.

제너레이터는 다음과 같은 상황에서 매우 유용하다.

대용량 데이터 처리 시 메모리 절약
시간이 오래 걸리는 작업을 필요할 때만 실행
무한한 데이터 스트림 처리
"""